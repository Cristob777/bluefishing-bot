create table if not exists products (
  url text primary key,
  name text not null,
  price text,
  category text,
  product_type text,
  brand text,
  updated_at timestamptz not null default now()
);

create table if not exists product_attributes (
  product_url text primary key references products(url) on delete cascade,
  target_species text[] not null default '{}',
  water_type text[] not null default '{}',
  fishing_position text[] not null default '{}',
  technique text[] not null default '{}',
  experience_level text,
  verified_notes text,
  use_case text,
  extra jsonb not null default '{}'::jsonb,
  source_url text,
  source_hash text,
  extraction_method text,
  extraction_confidence double precision,
  evidence jsonb not null default '[]'::jsonb,
  updated_by text,
  updated_at timestamptz not null default now()
);

create table if not exists chat_feedback (
  id uuid primary key default gen_random_uuid(),
  session_id text not null,
  source_channel text,
  user_message text not null,
  bot_response text not null,
  correction text,
  debug_snapshot jsonb not null default '{}'::jsonb,
  status text not null default 'flagged',
  flagged_by text,
  resolved_by text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists bot_sessions (
  session_id text primary key,
  history jsonb not null default '[]'::jsonb,
  known_context jsonb not null default '{}'::jsonb,
  last_classification jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists processed_whatsapp_messages (
  message_id text primary key,
  from_phone text,
  created_at timestamptz not null default now()
);

create table if not exists bot_events (
  id bigint generated by default as identity primary key,
  session_id text not null,
  channel text not null default 'whatsapp',
  user_message text not null,
  bot_response text,
  intent text,
  products jsonb not null default '[]'::jsonb,
  latency_ms integer,
  handoff boolean not null default false,
  route text,
  llm_usage jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists handoff_requests (
  id bigint generated by default as identity primary key,
  session_id text not null,
  phone text,
  intent text,
  last_message text,
  status text not null default 'open' check (status in ('open','contacted','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists bot_sessions_updated_at_idx on bot_sessions(updated_at desc);
create index if not exists processed_whatsapp_messages_created_idx on processed_whatsapp_messages(created_at desc);
create index if not exists bot_events_created_at_idx on bot_events(created_at desc);
create index if not exists bot_events_session_id_idx on bot_events(session_id);
create index if not exists handoff_requests_status_idx on handoff_requests(status, created_at desc);

-- CRM (ver db/migrations/003_crm_contacts.sql para instalaciones existentes)
create table if not exists contacts (
  id bigint generated by default as identity primary key,
  channel text not null default 'whatsapp' check (channel in ('whatsapp','web','instagram','chatwoot')),
  external_id text not null,
  session_id text not null,
  name text,
  phone text,
  stage text not null default 'nuevo'
    check (stage in ('nuevo','interesado','cotizado','compro','perdido')),
  assigned_to text,
  message_count integer not null default 0,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (channel, external_id),
  unique (session_id)
);
create index if not exists contacts_last_seen_idx on contacts(last_seen_at desc);
create index if not exists contacts_stage_idx on contacts(stage, last_seen_at desc);
create index if not exists handoff_requests_session_id_idx on handoff_requests(session_id);

-- Vista de lectura para el panel del dueño: contacto + actividad + handoff abierto.
create or replace view crm_contact_overview as
select
  c.*,
  (select count(*)::int from bot_events e where e.session_id = c.session_id) as turns,
  (select max(e.created_at) from bot_events e where e.session_id = c.session_id) as last_event_at,
  exists (select 1 from handoff_requests h where h.session_id = c.session_id and h.status = 'open') as handoff_open
from contacts c;

-- Atomic CRM sync (ver db/migrations/004_atomic_crm_sync.sql)
create table if not exists atomic_crm_sync (
  entity text not null check (entity in ('contact','deal','handoff_note')),
  source_id text not null,
  target_id bigint not null,
  payload_hash text,
  synced_at timestamptz not null default now(),
  primary key (entity, source_id)
);
create index if not exists atomic_crm_sync_synced_idx on atomic_crm_sync(synced_at desc);
