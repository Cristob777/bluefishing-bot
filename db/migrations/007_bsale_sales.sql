-- Ventas Bsale (web + tienda física) para atribución conversación -> venta. Idempotente.
-- Solo la cuenta del operador (Blue Fishing). Teléfono/correo se guardan solo en las ventas
-- atribuidas a un contacto (minimización de datos); el resto queda para el total de la tienda.
create table if not exists bsale_sales (
  id bigint generated by default as identity primary key,
  document_id bigint not null unique,
  number text,
  code_sii int,
  total numeric(14,2) not null default 0,
  emitted_at timestamptz not null,
  office_id int,
  phone text,
  email text,
  contact_id bigint references contacts(id) on delete set null,
  attributed_session text,
  synced_at timestamptz not null default now()
);
create index if not exists bsale_sales_emitted_idx on bsale_sales (emitted_at desc);
create index if not exists bsale_sales_contact_idx on bsale_sales (contact_id) where contact_id is not null;

create table if not exists bsale_sync_state (
  scope text primary key,            -- 'operator'
  last_sync_at timestamptz,
  last_emission_at timestamptz,      -- última fecha de emisión vista (cursor incremental)
  last_error text
);
