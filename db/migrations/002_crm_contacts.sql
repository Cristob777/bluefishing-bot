-- CRM: contactos. Idempotente; se puede correr varias veces.
-- Instalaciones nuevas: incluido en db/schema.sql (docker-entrypoint-initdb.d).
-- Instalaciones existentes: aplicar manualmente:
--   psql "$DATABASE_URL" -f db/migrations/002_crm_contacts.sql
--
-- El historial NO se duplica: contacts.session_id ('wa:<telefono>') es la clave
-- de unión con bot_sessions.session_id, bot_events.session_id y
-- handoff_requests.session_id, que ya guardan historial, turnos y handoffs.

create table if not exists contacts (
  id bigint generated by default as identity primary key,
  channel text not null default 'whatsapp' check (channel in ('whatsapp','web','instagram')),
  external_id text not null,
  session_id text not null,
  name text,
  phone text,
  stage text not null default 'nuevo'
    check (stage in ('nuevo','interesado','cotizado','compro','perdido')),
  assigned_to text,
  message_count integer not null default 0,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (channel, external_id),
  unique (session_id)
);
create index if not exists contacts_last_seen_idx on contacts(last_seen_at desc);
create index if not exists contacts_stage_idx on contacts(stage, last_seen_at desc);
create index if not exists handoff_requests_session_id_idx on handoff_requests(session_id);

-- Vista de lectura para el panel del dueño: contacto + actividad + handoff abierto.
create or replace view crm_contact_overview as
select
  c.*,
  (select count(*)::int from bot_events e where e.session_id = c.session_id) as turns,
  (select max(e.created_at) from bot_events e where e.session_id = c.session_id) as last_event_at,
  exists (select 1 from handoff_requests h where h.session_id = c.session_id and h.status = 'open') as handoff_open
from contacts c;
