-- CRM multiempresa + atribución de ventas WooCommerce. Idempotente.
-- tenant_id NULL = cuenta del operador (número y tienda del .env). Los datos previos
-- (instalación de una sola empresa) quedan así, sin perder nada: backfill seguro.

alter table contacts add column if not exists tenant_id uuid references tenants(id) on delete cascade;
alter table contacts add column if not exists email text;

-- Backfill: contactos de WhatsApp cuyo session_id ya es wa:<tenant>:<tel> se asignan a esa empresa.
update contacts c set tenant_id = t.id
  from tenants t
 where c.tenant_id is null and c.session_id like 'wa:' || t.id::text || ':%';
-- Contactos WhatsApp creados antes de 005 (sin empresa): si ese teléfono habló SOLO con una
-- empresa y nunca con el número del operador, se asignan a esa empresa. Si hay ambigüedad, quedan en el operador.
with m as (
  select split_part(e.session_id, ':', 3) phone, min(split_part(e.session_id, ':', 2)) tid, count(distinct split_part(e.session_id, ':', 2)) n
    from bot_events e where e.session_id ~ '^wa:[0-9a-f-]{36}:' group by 1)
update contacts c set tenant_id = m.tid::uuid, session_id = 'wa:' || m.tid || ':' || c.external_id
  from m
 where c.tenant_id is null and c.channel = 'whatsapp' and c.external_id = m.phone and m.n = 1
   and not exists (select 1 from bot_events o where o.session_id = 'wa:' || c.external_id)
   and not exists (select 1 from contacts x where x.session_id = 'wa:' || m.tid || ':' || c.external_id);

-- Unicidad por empresa (antes era global por canal+id).
alter table contacts drop constraint if exists contacts_channel_external_id_key;
create unique index if not exists contacts_tenant_channel_ext_uidx
  on contacts ((coalesce(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid)), channel, external_id);
create index if not exists contacts_tenant_stage_idx on contacts (tenant_id, stage, last_seen_at desc);

-- Chat web por empresa: clave pública del widget + orígenes permitidos.
alter table tenants add column if not exists widget_key text;
update tenants set widget_key = encode(gen_random_bytes(12), 'hex') where widget_key is null;
alter table tenants alter column widget_key set default encode(gen_random_bytes(12), 'hex');
create unique index if not exists tenants_widget_key_uidx on tenants (widget_key);
alter table tenants add column if not exists widget_origins text[] not null default '{}';

-- Historial de cambios de etapa (auditoría del embudo).
create table if not exists contact_stage_events (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references contacts(id) on delete cascade,
  tenant_id uuid references tenants(id) on delete cascade,
  from_stage text, to_stage text not null, actor text not null,
  created_at timestamptz not null default now()
);

-- Pedidos WooCommerce (solo lectura) y su atribución a conversaciones del bot.
create table if not exists woo_orders (
  id bigint generated by default as identity primary key,
  tenant_id uuid references tenants(id) on delete cascade,
  order_id bigint not null,
  status text not null,
  total numeric(14,2) not null default 0,
  currency text,
  phone text, email text,
  order_created_at timestamptz not null,
  contact_id bigint references contacts(id) on delete set null,
  attributed_session text,
  synced_at timestamptz not null default now()
);
create unique index if not exists woo_orders_tenant_order_uidx
  on woo_orders ((coalesce(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid)), order_id);
create index if not exists woo_orders_tenant_date_idx on woo_orders (tenant_id, order_created_at desc);

create table if not exists woo_sync_state (
  tenant_key text primary key,       -- tenant uuid o 'operator'
  last_sync_at timestamptz, last_error text
);
